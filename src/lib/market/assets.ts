export function searchAssets(query: string, limit = 12): Asset[] {
  const q = query.trim().toLowerCase().replace("/", "");
  if (!q) return ASSETS.filter((asset) => DEFAULT_WATCHLIST_SYMBOLS.includes(asset.id)).slice(0, limit);

  const scored = ASSETS.map((asset) => {
    const symbol = asset.symbol.toLowerCase();
    const flatSymbol = symbol.replace("/", "");
    const name = asset.name.toLowerCase();
    const keywords = (asset.keywords ?? []).join(" ");
    let score = 0;
    if (flatSymbol === q || asset.id.toLowerCase() === q) score = 100;
    else if (flatSymbol.startsWith(q)) score = 80;
    else if (symbol.startsWith(q)) score = 75;
    else if (name.startsWith(q)) score = 70;
    else if (name.includes(q)) score = 55;
    else if (flatSymbol.includes(q)) score = 50;
    else if (keywords.includes(q)) score = 40;
    else if (asset.class.toLowerCase().includes(q)) score = 20;
    else if (asset.exchange.toLowerCase().includes(q)) score = 10;
    return { asset, score };
  })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score || a.asset.symbol.localeCompare(b.asset.symbol));

  return scored.slice(0, limit).map((entry) => entry.asset);
}
