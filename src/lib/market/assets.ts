const ASSET_MAP = new Map(ASSETS.map((asset) => [asset.id, asset]));

export const DEFAULT_SYMBOL = "BTCUSD";

export function getAsset(symbolOrId: string): Asset | undefined {
  const normalized = symbolOrId.trim().toLowerCase();
  return (
    ASSET_MAP.get(symbolOrId) ??
    ASSETS.find(
      (asset) =>
        asset.id.toLowerCase() === normalized ||
        asset.symbol.toLowerCase() === normalized ||
        asset.symbol.replace("/", "").toLowerCase() === normalized,
    )
  );
}

export function requireAsset(symbolOrId: string): Asset {
  const asset = getAsset(symbolOrId);
  if (!asset) throw new Error(`Unknown asset: ${symbolOrId}`);
  return asset;
}

export function getAssetsByClass(assetClass: Asset["class"] | "all"): Asset[] {
  if (assetClass === "all") return ASSETS;
  return ASSETS.filter((asset) => asset.class === assetClass);
}

